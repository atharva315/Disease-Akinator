-- Disease Akinator PostgreSQL schema
-- Phase 2: database implementation
-- Execute this file on the production branch, database "disease_akinator",
-- using the administrative role "neondb_owner".
--
-- The application role "disease_akinator_app" receives DML access only.
-- It must not be used to create or alter schema objects.

BEGIN;

-- ---------------------------------------------------------------------
-- 1. DOCTORS
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.doctors (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(100) NOT NULL
                            CHECK (BTRIM(full_name) <> ''),
    age                 SMALLINT NOT NULL
                            CHECK (age BETWEEN 25 AND 80),
    degree              VARCHAR(50) NOT NULL
                            CHECK (degree IN (
                                'MBBS', 'MD', 'MS', 'DM', 'MCh',
                                'BDS', 'MDS', 'DNB',
                                'BAMS', 'BHMS', 'BUMS',
                                'BSMS', 'BNYS', 'Other'
                            )),
    custom_degree       VARCHAR(100),
    hospital            VARCHAR(150),
    city                VARCHAR(100),
    email               VARCHAR(254) NOT NULL,
    password_hash       TEXT NOT NULL,
    degree_file_id      VARCHAR(24) NOT NULL UNIQUE
                            CHECK (degree_file_id ~ '^[0-9a-fA-F]{24}$'),
    degree_filename     VARCHAR(255) NOT NULL
                            CHECK (BTRIM(degree_filename) <> ''),
    degree_size_bytes   BIGINT NOT NULL
                            CHECK (degree_size_bytes BETWEEN 1 AND 10485760),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT doctors_email_normalized
        CHECK (email = LOWER(BTRIM(email))),
    CONSTRAINT doctors_email_unique
        UNIQUE (email),
    CONSTRAINT doctors_custom_degree_required
        CHECK (
            (degree = 'Other'
                AND custom_degree IS NOT NULL
                AND BTRIM(custom_degree) <> '')
            OR
            (degree <> 'Other' AND custom_degree IS NULL)
        )
);

-- ---------------------------------------------------------------------
-- 2. SYMPTOM CONTRIBUTIONS
-- One parent record per doctor submission.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.symptom_contributions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id       BIGINT NOT NULL
                        REFERENCES public.doctors(id) ON DELETE RESTRICT,
    disease_name    VARCHAR(200) NOT NULL
                        CHECK (BTRIM(disease_name) <> ''),
    notes           TEXT,
    submitted_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 3. SYMPTOM CONTRIBUTION ITEMS
-- One row per symptom, preserving the order entered by the doctor.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.symptom_contribution_items (
    contribution_id BIGINT NOT NULL
                        REFERENCES public.symptom_contributions(id)
                        ON DELETE CASCADE,
    position        SMALLINT NOT NULL CHECK (position > 0),
    symptom_text    VARCHAR(300) NOT NULL
                        CHECK (BTRIM(symptom_text) <> ''),
    PRIMARY KEY (contribution_id, position)
);

-- Prevent the same symptom being entered more than once in a submission,
-- ignoring case and surrounding whitespace.
CREATE UNIQUE INDEX IF NOT EXISTS
    uq_symptom_items_contribution_symptom
ON public.symptom_contribution_items
    (contribution_id, LOWER(BTRIM(symptom_text)));

-- ---------------------------------------------------------------------
-- 4. IMAGE CONTRIBUTIONS
-- Image bytes live in MongoDB GridFS. PostgreSQL stores the reference
-- and structured metadata, including the submitting doctor.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.image_contributions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id           BIGINT NOT NULL
                            REFERENCES public.doctors(id) ON DELETE RESTRICT,
    disease_name        VARCHAR(200) NOT NULL
                            CHECK (BTRIM(disease_name) <> ''),
    mongo_file_id       VARCHAR(24) NOT NULL UNIQUE
                            CHECK (mongo_file_id ~ '^[0-9a-fA-F]{24}$'),
    image_filename      VARCHAR(255) NOT NULL
                            CHECK (BTRIM(image_filename) <> ''),
    content_type        VARCHAR(30) NOT NULL
                            CHECK (content_type IN ('image/jpeg', 'image/png')),
    file_size_bytes     BIGINT NOT NULL
                            CHECK (file_size_bytes BETWEEN 1 AND 5242880),
    notes               TEXT,
    submitted_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 5. INDEXES FOR COMMON LOOKUPS AND CONTRIBUTION STATISTICS
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_symptom_contributions_doctor_date
    ON public.symptom_contributions (doctor_id, submitted_at DESC);

CREATE INDEX IF NOT EXISTS idx_symptom_contributions_disease
    ON public.symptom_contributions (LOWER(disease_name));

CREATE INDEX IF NOT EXISTS idx_symptom_items_text
    ON public.symptom_contribution_items (LOWER(symptom_text));

CREATE INDEX IF NOT EXISTS idx_image_contributions_doctor_date
    ON public.image_contributions (doctor_id, submitted_at DESC);

CREATE INDEX IF NOT EXISTS idx_image_contributions_disease
    ON public.image_contributions (LOWER(disease_name));

-- ---------------------------------------------------------------------
-- 6. APPLICATION ROLE PERMISSIONS
-- The application can read and modify records, but cannot manage schema.
-- ---------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE
ON ALL TABLES IN SCHEMA public
TO disease_akinator_app;

GRANT USAGE, SELECT, UPDATE
ON ALL SEQUENCES IN SCHEMA public
TO disease_akinator_app;

-- Keep default privileges aligned for future objects created by owner.
ALTER DEFAULT PRIVILEGES
FOR ROLE neondb_owner
IN SCHEMA public
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES
TO disease_akinator_app;

ALTER DEFAULT PRIVILEGES
FOR ROLE neondb_owner
IN SCHEMA public
GRANT USAGE, SELECT, UPDATE ON SEQUENCES
TO disease_akinator_app;

COMMIT;
